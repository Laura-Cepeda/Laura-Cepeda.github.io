# Dictionary example
# This dictionary maps keys to values: string -> int, int -> string, string -> string
dic = {"a": 2, 4: "abc", "c": "hello world"}

# Access value with key 4
print(dic[4])  # Output: abc

# Create a new dictionary
dict = {}
dict["firstname"] = "Fabricio"
dict["lastname"] = "Ramos"
dict["gender"] = "Female"
# Print the dictionary
print(dict)  # Output: {'firstname': 'Fabricio', 'lastname': 'Ramos'}
print(dict["lastname"])