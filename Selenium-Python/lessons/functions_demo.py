# Define a function called GreetMe that takes one parameter called 'name'
def GreetMe(name):
    # This line runs when the function is called
    # It prints a greeting message by combining (concatenating) "Good morning" with the value of 'name'
    print("Good morning" + name)

# Define a function called AddIntegers that takes two parameters: 'a' and 'b'
def AddIntegers(a, b):
    # This line runs when the function is called
    # It prints the result of adding 'a' and 'b' together
    print(a + b)

# Call (run) the GreetMe function and pass " laura Cepeda" as the name
GreetMe(" laura Cepeda")

# Call the AddIntegers function and pass 2 and 3 as the values to add
AddIntegers(2, 3)